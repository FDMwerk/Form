import assert from 'node:assert/strict';
import {createViewerHarness} from './viewer-test-harness.mjs';
const h=createViewerHarness();
assert.equal(h.read('viewportDisplay.mode'),'edges');
assert.equal(h.read('viewportCameras.projection'),'orthographic');
// The custom grid shader writes display RGB directly (no output color chunk).
// A light gray must therefore remain ~0.69, not accidentally become linear ~0.43.
for(const channel of ['r','g','b'])assert.ok(h.read('grid.material.uniforms.gridColor.value.'+channel)>.66&&h.read('grid.material.uniforms.gridColor.value.'+channel)<.73,'Light grid gray was incorrectly linearized');
assert.ok(h.read('grid.material.uniforms.gridOpacity.value')<=.28,'Fine grid should remain subtle');
h.click('#background-menu');
assert.equal(h.document.querySelector('#background-panel').hidden,false);
h.click('[data-background-preset="dark"]');
assert.equal(h.read('scene.background.getHexString()'),'24272d');
assert.equal(h.read('viewportPrefs.backgroundColor'),'#24272d');
assert.equal(h.messages.at(-1).value.backgroundColor,'#24272d');
h.click('#background-grid');
assert.equal(h.read('grid.visible'),false);
await h.load('samples/Montageblock.stl');
assert.equal(h.read('grid.visible'),false,'Import must preserve hidden grid');
assert.equal(h.read('scene.background.getHexString()'),'24272d');
for(const channel of ['r','g','b'])assert.ok(h.read('grid.material.uniforms.gridColor.value.'+channel)>.70&&h.read('grid.material.uniforms.gridColor.value.'+channel)<.80,'Rebuilt dark grid lost display-RGB contrast');
assert.ok(h.read('grid.material.uniforms.extent.value')>=30);
assert.ok(h.read('grid.material.uniforms.extent.value')<h.read('radius')*3,'Small-model grid still has a giant nonfading minimum');
const extent=h.read('grid.material.uniforms.extent.value'),cornerRadius=h.read('Math.hypot(camera.right-camera.left,camera.top-camera.bottom)/(2*camera.zoom)');
const transition=Math.min(1,Math.max(0,(cornerRadius-extent*.18)/(extent*.9-extent*.18)));
assert.ok(1-transition*transition*(3-2*transition)<.6,'Grid does not visibly fade towards the fitted viewport corners');
h.click('#cut');
assert.ok(h.read('sectionHighlight.group.children.some(line=>line.visible)'));
const contour=h.read('sectionHighlight.group.children[0].geometry');
h.click('[data-background-preset="light"]');
assert.equal(h.read('cutEnabled'),true,'Background must preserve section');
for(const channel of ['r','g','b'])assert.ok(h.read('grid.material.uniforms.gridColor.value.'+channel)>.66&&h.read('grid.material.uniforms.gridColor.value.'+channel)<.73,'Switching back to light must restore the raw shader gray');
assert.equal(h.read('sectionHighlight.group.children[0].geometry'),contour);
h.click('#grid');
assert.equal(h.read('grid.visible'),true);
h.input('#background-color','#f4eabc');
assert.equal(h.read('scene.background.getHexString()'),'f4eabc');
h.window.applyViewportSettings({backgroundColor:'invalid',showGrid:'bad'});
assert.equal(h.read('scene.background.getHexString()'),'fafafa');
assert.equal(h.read('grid.visible'),true);
h.click('#display-menu');
assert.equal(h.document.querySelector('#background-panel').hidden,true);
h.click('#background-menu');
assert.equal(h.document.querySelector('#display-panel').hidden,true);
h.key('Escape');
assert.equal(h.document.querySelector('#background-panel').hidden,true);
h.click('[data-background-preset="warm"]');
h.click('#settings-reset');
assert.equal(h.read('scene.background.getHexString()'),'fafafa');
assert.equal(h.read('grid.visible'),true);
console.log('Background UI: raw shader gray/contrast and small-model fitted fade, presets, persistence payload, custom/invalid colors, import/grid and menu interactions passed.');
