import assert from 'node:assert/strict';
import {createViewerHarness} from './viewer-test-harness.mjs';
const h=createViewerHarness(), d=h.document;
assert.equal(d.querySelector('#show-print').hidden,true);
assert.equal(d.querySelector('#donate').hidden,true);
h.click('#donate');assert.equal(h.messages.includes('donate'),false);
h.window.applyNativeCapabilities({donations:'true'});
assert.equal(d.querySelector('#donate').hidden,true);
h.window.applyNativeCapabilities({donations:true});
assert.equal(d.querySelector('#donate').hidden,false);
h.click('#donate');assert.equal(h.messages.at(-1),'donate');
h.window.applyNativeCapabilities({donations:false});
h.click('#donate');assert.equal(h.messages.filter(m=>m==='donate').length,1);
h.window.applyPrintSoftware([{id:'com.bambulab.bambu-studio',name:'Bambu Studio'}]);
assert.equal(d.querySelector('#show-print').hidden,false);
assert.equal(d.querySelector('#show-print').disabled,true);
await h.load('samples/Montageblock.stl');
assert.equal(d.querySelector('#show-print').disabled,false);
h.click('#cut');h.click('#show-print');
assert.equal(d.body.classList.contains('inspecting'),true);
assert.equal(d.querySelector('#inspector').classList.contains('print-mode'),true);
assert.equal(d.querySelector('#print-info').open,true);
h.click('#info');
assert.equal(d.querySelector('#inspector').classList.contains('file-mode'),true);
assert.equal(d.body.classList.contains('inspecting'),true);
assert.equal(h.read('cutEnabled'),true);
h.click('#show-print');h.click('#remove');
assert.equal(d.body.classList.contains('inspecting'),false);
assert.equal(d.querySelector('#show-print').disabled,true);
h.window.applyPrintSoftware([]);
assert.equal(d.querySelector('#show-print').hidden,true);
h.click('#feedback');assert.equal(h.messages.at(-1),'feedback');
assert.ok(d.querySelector('#legal svg'));
assert.ok(d.querySelector('#settings svg'));
console.log('PASS native donation gate, print detection/selection gate, file↔print sidebar modes, section preservation and unload cleanup.');
